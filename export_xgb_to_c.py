"""
export_xgb_to_c.py - turn a trained binary XGBoost model (JSON) into a C header for the ESP32.

    python export_xgb_to_c.py irrigation_model.json model.h

Then in the sketch:
    #include "model.h"
    float x[N_FEATURES] = {soil, temp, hum, reservoir, rain};   // SAME order as training
    int irrigate = xgboostPredict(x);
Trees are stored as const arrays (flash, not RAM). A 30-tree, depth-3 model is ~3 KB.
"""
import json, math, sys

src, dst = sys.argv[1], sys.argv[2]
m = json.load(open(src))["learner"]
trees = m["gradient_booster"]["model"]["trees"]
base = float(m["learner_model_param"]["base_score"].strip("[]"))
margin0 = math.log(base / (1 - base)) if 0 < base < 1 else 0.0   # logistic objective
n_feat = int(m["learner_model_param"]["num_feature"])

def cf(v):
    """C float literal. A whole number like 40 or 0 must become 40.0f / 0.0f ('40f' is invalid C++)."""
    t = f"{float(v):.8g}"
    if not any(c in t for c in ".eEn"):
        t += ".0"
    return t + "f"


nodes = []          # flat arrays across all trees
roots = []
for t in trees:
    off = len(nodes)
    roots.append(off)
    for i in range(len(t["left_children"])):
        left, right = t["left_children"][i], t["right_children"][i]
        leaf = left == -1
        nodes.append((
            -1 if leaf else t["split_indices"][i],
            t["base_weights"][i] if leaf else t["split_conditions"][i],   # leaf value or threshold
            -1 if leaf else off + left,
            -1 if leaf else off + right,
        ))

out = ["// Auto-generated by export_xgb_to_c.py. Do not edit.", "#pragma once", "#include <math.h>",
       f"#define N_FEATURES {n_feat}", f"#define N_TREES {len(trees)}",
       f"const float XGB_BASE_MARGIN = {cf(margin0)};",
       "const int16_t XGB_FEAT[] PROGMEM = {" + ",".join(str(n[0]) for n in nodes) + "};",
       "const float   XGB_VAL[]  PROGMEM = {" + ",".join(cf(n[1]) for n in nodes) + "};",
       "const int16_t XGB_LEFT[] PROGMEM = {" + ",".join(str(n[2]) for n in nodes) + "};",
       "const int16_t XGB_RIGHT[] PROGMEM = {" + ",".join(str(n[3]) for n in nodes) + "};",
       "const int16_t XGB_ROOT[] PROGMEM = {" + ",".join(map(str, roots)) + "};",
       """
// returns 1 = irrigate, 0 = don't
int xgboostPredict(const float *x) {
  float margin = XGB_BASE_MARGIN;
  for (int t = 0; t < N_TREES; t++) {
    int n = XGB_ROOT[t];
    while (XGB_FEAT[n] >= 0)
      n = (x[XGB_FEAT[n]] < XGB_VAL[n]) ? XGB_LEFT[n] : XGB_RIGHT[n];
    margin += XGB_VAL[n];
  }
  return (1.0f / (1.0f + expf(-margin))) >= 0.5f ? 1 : 0;
}"""]
open(dst, "w").write("\n".join(out) + "\n")
print(f"{len(trees)} trees, {len(nodes)} nodes, ~{len(nodes)*10} bytes of flash -> {dst}")